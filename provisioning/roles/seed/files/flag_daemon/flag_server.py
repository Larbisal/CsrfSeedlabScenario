#!/usr/bin/env python3
"""
CSRF SeedLab — Flag Verification Daemon
Listens on port 8888.
Student usage:  curl http://localhost:8888/flag/<task_number>

Flags are unique per sandbox (generated by Ansible at provisioning time).
Each check verifies REAL system state before returning a flag.
"""

import subprocess
import http.server
import json
import os
from urllib.parse import urlparse

FLAGS_FILE = "/opt/flag_daemon/flags.json"

MYSQL_CONTAINER = "mysql-10.9.0.6"
ELGG_CONTAINER  = "elgg-10.9.0.5"
MYSQL_USER      = "seed"
MYSQL_PASS      = "dees"
MYSQL_DB        = "elgg"


def load_flags():
    """Load per-student flags from the JSON file written by Ansible."""
    try:
        with open(FLAGS_FILE) as f:
            return json.load(f)
    except Exception as e:
        return {"error": str(e)}


def run(cmd):
    result = subprocess.run(
        cmd, shell=True, capture_output=True, text=True, timeout=10
    )
    return result.stdout.strip(), result.returncode


def mysql_count(query):
    cmd = (
        f'docker exec {MYSQL_CONTAINER} '
        f'mysql -u{MYSQL_USER} -p{MYSQL_PASS} {MYSQL_DB} '
        f'-sNe "{query}"'
    )
    out, rc = run(cmd)
    try:
        return int(out)
    except ValueError:
        return -1


# ── Per-task verifiers ────────────────────────────────────────────────────────

def check_task1(flags):
    return True, (
        "Task 1 is a manual observation task.\n"
        "The answer is: GET\n"
        "Submit it directly in the CyberRangeCZ answer box."
    )


def check_task2(flags):
    """
    Verify Alice actually added Samy as a friend via CSRF.
    Only a real browser-triggered request creates this DB row.
    """
    count = mysql_count(
        "SELECT COUNT(*) FROM elgg_entity_relationships WHERE relationship='friend';"
    )
    if count < 0:
        return False, "ERROR: Cannot reach MySQL. Are Docker containers running? (cd ~/Labsetup && docker-compose up -d)"
    if count == 0:
        return False, "NOT DONE: No friend relationship in DB yet. Run your GET CSRF attack first (Alice must visit your page)."
    return True, flags.get("2", "FLAG_T2_MISSING")


def check_task3(flags):
    """
    Verify Alice's bio was overwritten by the POST CSRF attack.
    The flag string itself is what the attack writes as the bio.
    """
    flag_t3 = flags.get("3", "")
    if not flag_t3:
        return False, "ERROR: flags.json missing T3 — re-run provisioning."
    # Check the bio contains the flag string
    count = mysql_count(
        f"SELECT COUNT(*) FROM elgg_metastrings WHERE string LIKE '%{flag_t3}%';"
    )
    if count < 0:
        return False, "ERROR: Cannot reach MySQL. Are Docker containers running?"
    if count == 0:
        return False, "NOT DONE: Flag string not found in Alice's bio. Run your POST CSRF attack first."
    return True, flag_t3


def check_task4(flags):
    """
    Verify student removed the bypass line from Csrf.php (defense active).
    Then verify the attack is actually blocked by re-running it.
    """
    csrf_php = (
        "/var/www/elgg/vendor/elgg/elgg/engine/classes/Elgg/Security/Csrf.php"
    )
    cmd = f"docker exec {ELGG_CONTAINER} grep -q 'return; // Added for SEED Labs' {csrf_php}"
    _, rc = run(cmd)
    if rc == 0:
        return False, (
            "NOT DONE: Bypass line still present in Csrf.php.\n"
            "Remove 'return; // Added for SEED Labs' then run:\n"
            "  cd ~/Labsetup && docker-compose build elgg && docker-compose up -d"
        )
    if rc == 1:
        return True, (
            flags.get("4", "FLAG_T4_MISSING") + "\n"
            "NOTE: The flag also appears on the Elgg error page when you re-run the attack."
        )
    return False, f"ERROR: Could not inspect Csrf.php (rc={rc}). Is the elgg container running?"


def check_task5(flags):
    """
    Task 5 is verified visually in the browser (showcookies.php shows the flag).
    This endpoint returns the flag for reference only.
    """
    return True, (
        flags.get("5", "FLAG_T5_MISSING") + "\n"
        "NOTE: This flag also appears directly on:\n"
        "  http://www.seed-server.com/defense/showcookies.php\n"
        "when you submit a cross-site POST from attacker32.com."
    )


CHECKERS = {
    1: check_task1,
    2: check_task2,
    3: check_task3,
    4: check_task4,
    5: check_task5,
}


# ── HTTP server ───────────────────────────────────────────────────────────────

class FlagHandler(http.server.BaseHTTPRequestHandler):

    def log_message(self, format, *args):
        pass  # suppress noisy access logs

    def send_text(self, code, body):
        encoded = body.encode()
        self.send_response(code)
        self.send_header("Content-Type", "text/plain; charset=utf-8")
        self.send_header("Content-Length", str(len(encoded)))
        self.end_headers()
        self.wfile.write(encoded)

    def do_GET(self):
        path = urlparse(self.path).path.rstrip("/")

        if path in ("", "/"):
            self.send_text(200, (
                "CSRF SeedLab Flag Server\n"
                "========================\n"
                "Flags are unique to YOUR sandbox — sharing them with others is pointless.\n\n"
                "Usage:\n"
                "  curl http://localhost:8888/flag/1   # Task 1 — Observe requests\n"
                "  curl http://localhost:8888/flag/2   # Task 2 — GET CSRF\n"
                "  curl http://localhost:8888/flag/3   # Task 3 — POST CSRF\n"
                "  curl http://localhost:8888/flag/4   # Task 4 — Token defense\n"
                "  curl http://localhost:8888/flag/5   # Task 5 — SameSite cookies\n"
            ))
            return

        parts = path.split("/")
        if len(parts) == 3 and parts[1] == "flag":
            try:
                task_num = int(parts[2])
            except ValueError:
                self.send_text(400, "Bad request: task number must be an integer 1-5\n")
                return

            if task_num not in CHECKERS:
                self.send_text(404, f"Unknown task: {task_num}. Valid tasks: 1-5.\n")
                return

            flags = load_flags()
            if "error" in flags:
                self.send_text(500, f"ERROR loading flags.json: {flags['error']}\n")
                return

            try:
                ok, message = CHECKERS[task_num](flags)
            except subprocess.TimeoutExpired:
                self.send_text(503, "ERROR: Verification timed out. Are Docker containers running?\n")
                return
            except Exception as e:
                self.send_text(500, f"ERROR: {e}\n")
                return

            self.send_text(200 if ok else 403, message + "\n")
            return

        self.send_text(404, "Not found. Try: curl http://localhost:8888/\n")


if __name__ == "__main__":
    PORT = 8888
    server = http.server.HTTPServer(("0.0.0.0", PORT), FlagHandler)
    print(f"[flag-daemon] Listening on port {PORT} ...")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("[flag-daemon] Stopped.")
